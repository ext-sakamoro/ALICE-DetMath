#!/usr/bin/env python3
"""Generate tests/data/sin_cos32_large_reference.txt: correctly rounded binary32
`sin` / `cos` for `|x| ≥ 2^13`.

From `2^13` on, `sin` / `cos` / `sin_cos` (binary32) reduce the argument in
double precision ([`sin64`] / [`cos64`], Payne–Hanek above `2^20·π/2`) and
round once to binary32. The reference is independent of every libm: each
input is an exact binary32 value, `mpmath` evaluates `sin` / `cos` at 600 bits
(enough for the reduction of `f32::MAX` ≈ 2^128 by π/2 with ~400 bits left),
and the result is rounded to the nearest binary32 (ties to even) by comparing
the candidates around it in high precision.

Inputs: the neighbours of `±2^13` (where the reduction switches), a geometric
sweep of 3000 values over `[2^13, f32::MAX]`, every power of two from `2^13`
to `2^127`, `f32::MAX`, and the binary32 values nearest `k·π/2` for 2000 `k`
spread over the whole range (there the result is small and its relative
accuracy depends on the reduction keeping every bit of `x mod π/2`). Each
input appears with both signs.

Each line: `<x bits> <sin(x) bits> <cos(x) bits>`, 8 hex digits each.

Usage: `uv run --with mpmath python3 scripts/gen_sin_cos32_large_reference.py`
(or any Python with mpmath installed). The output is deterministic.
"""

from __future__ import annotations

import struct
import sys

import mpmath as mp

mp.mp.prec = 600


def bits(v: float) -> int:
    return struct.unpack("<I", struct.pack("<f", v))[0]


def from_bits(b: int) -> float:
    return struct.unpack("<f", struct.pack("<I", b))[0]


def f32(v: float) -> float:
    return from_bits(bits(v))


def round_f32(v: mp.mpf) -> int:
    """Bits of the binary32 nearest `v` (ties to even); |v| ≤ 1 here."""
    if v == 0:
        return 0
    neg = v < 0
    a = -v if neg else v
    c = bits(f32(float(a)))
    best = None
    for b in (c - 1, c, c + 1):
        if b < 0:
            continue
        d = abs(mp.mpf(from_bits(b)) - a)
        if best is None or d < best[0] or (d == best[0] and b % 2 == 0):
            best = (d, b)
    return best[1] | (0x80000000 if neg else 0)


def main() -> None:
    xs = set()
    lo = bits(8192.0)
    for d in range(-8, 9):
        xs.add(lo + d)
    xs.update(bits(2.0 ** e) for e in range(13, 128))
    xs.add(0x7F7FFFFF)
    top = mp.log(mp.mpf(from_bits(0x7F7FFFFF)))
    base = mp.log(mp.mpf(8192))
    for i in range(3000):
        xs.add(bits(f32(float(mp.exp(base + (top - base) * i / 2999)))))
    half_pi = mp.pi / 2
    for i in range(2000):
        x = mp.exp(base + (top - base) * i / 1999)
        k = mp.nint(x / half_pi)
        xs.add(bits(f32(float(k * half_pi))))
    xs = sorted(b for b in xs if 8192.0 <= from_bits(b) <= from_bits(0x7F7FFFFF))
    out = sys.stdout
    out.write("# x sin(x) cos(x): IEEE 754 binary32 bits, correctly rounded (mpmath, 600 bits)\n")
    out.write("# generated by scripts/gen_sin_cos32_large_reference.py\n")
    for b in xs:
        for sb in (b, b | 0x80000000):
            x = mp.mpf(from_bits(sb))
            out.write(f"{sb:08x} {round_f32(mp.sin(x)):08x} {round_f32(mp.cos(x)):08x}\n")


if __name__ == "__main__":
    main()
