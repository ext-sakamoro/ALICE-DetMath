#!/usr/bin/env python3
"""Generate tests/data/tanh64_reference.txt and tests/data/hypot64_reference.txt: correctly rounded
tanh and hypot.

The references are independent of every libm: each input is an exact binary double, mpmath evaluates
the function at 400 bits, and the result is rounded to the nearest double (ties to even) by comparing
the three candidate doubles around it in high precision.

Inputs (all finite, seeded, so the output is deterministic):
- tanh: log-uniform |x| over [2^-60, 22] with a random sign; dense around x = 0.0039 (the region where
  an earlier small-argument formula reached 3 ulp); both branch thresholds of the implementation
  (ln(5/3)/2 and ln(3)/2) and their neighbours; the saturation edge near 19.06 and 22; the worst case
  an independent sweep found for the earlier formula.
- hypot: log-uniform x over the whole range with y = x * ratio, ratio log-uniform in [2^-60, 1]; both
  scaling thresholds (2^500 and 2^-500) where the arguments are rescaled; subnormal pairs; the worst
  case an independent sweep found for the earlier formula.

Each line: `<x bits> <tanh(x) bits> <frac bits>` / `<x bits> <y bits> <hypot(x, y) bits> <frac bits>`, 16
hex digits each: the correctly rounded value `hi`, and `(true − hi) / (next_up(hi) − hi)` (in `[-0.5, 0.5]`
up to the spacing below a power of two), so a test can measure the error against the true value in units of
the last place at every magnitude, subnormal results included (a low part `true − hi` would underflow there).
`N_TANH` / `N_HYPOT` (environment) change the number of random inputs (a larger sweep for measuring;
the committed tables use the defaults). `--out DIR` writes into another directory.

Usage: `uv run --with mpmath python3 scripts/gen_tanh_hypot64_reference.py`
"""

from __future__ import annotations

import math
import os
import random
import struct
import sys

import mpmath

mpmath.mp.prec = 400
SEED = 20261029


def bits(x: float) -> int:
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def round_nearest(v: mpmath.mpf) -> float:
    """The double nearest to v (ties to even), decided in high precision."""
    c = float(v)
    best = None
    for cand in (math.nextafter(c, -math.inf), c, math.nextafter(c, math.inf)):
        d = abs(mpmath.mpf(cand) - v)
        key = (d, bits(cand) & 1)
        if best is None or key < best[0]:
            best = (key, cand)
    return best[1]


def frac(v: mpmath.mpf, hi: float) -> float:
    """(v - hi) in units of the spacing above |hi|, signed as v - hi"""
    up = abs(hi)
    spacing = math.nextafter(up, math.inf) - up
    return float((v - mpmath.mpf(hi)) / mpmath.mpf(spacing))


def log_uniform(rng: random.Random, lo: float, hi: float) -> float:
    return math.exp(rng.uniform(math.log(lo), math.log(hi)))


def tanh_inputs(rng: random.Random, n: int) -> list[float]:
    xs: list[float] = []
    for _ in range(n):
        xs.append(log_uniform(rng, 2.0**-60, 22.0) * rng.choice((1.0, -1.0)))
    for _ in range(n // 4):
        xs.append(rng.uniform(0.001, 0.01))
    for t in (math.log(5 / 3) / 2, math.log(3) / 2, 19.0615474653985, 22.0):
        x = t
        for _ in range(64):
            xs.append(x)
            x = math.nextafter(x, math.inf)
        x = t
        for _ in range(64):
            x = math.nextafter(x, -math.inf)
            xs.append(x)
        for _ in range(n // 16):
            xs.append(t * (1.0 + rng.uniform(-1e-3, 1e-3)))
    xs.append(0.0038994723714718257)
    return xs


def hypot_inputs(rng: random.Random, n: int) -> list[tuple[float, float]]:
    ps: list[tuple[float, float]] = []
    for _ in range(n):
        x = log_uniform(rng, 2.0**-1000, 2.0**1000)
        ps.append((x, x * log_uniform(rng, 2.0**-60, 1.0)))
    for edge in (2.0**500, 2.0**-500):
        for _ in range(n // 8):
            x = edge * rng.uniform(0.5, 2.0)
            ps.append((x, x * log_uniform(rng, 2.0**-30, 1.0)))
    for _ in range(n // 16):
        x = rng.randint(1, 2**52) * 2.0**-1074
        ps.append((x, rng.randint(1, 2**52) * 2.0**-1074))
    ps.append((4.653460818220163e150, 8.663017399024956e144))
    return ps


def main() -> int:
    out = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else os.path.join(os.path.dirname(__file__), "..", "tests", "data")
    rng = random.Random(SEED)
    n_tanh = int(os.environ.get("N_TANH", "4000"))
    n_hypot = int(os.environ.get("N_HYPOT", "4000"))
    with open(os.path.join(out, "tanh64_reference.txt"), "w") as f:
        f.write(f"# x tanh(x) frac: IEEE 754 binary64 bits, correctly rounded, and (true - rounded) / its ulp (mpmath, 400 bits)\n")
        f.write(f"# generated by scripts/gen_tanh_hypot64_reference.py (seed {SEED}, N_TANH {n_tanh})\n")
        for x in tanh_inputs(rng, n_tanh):
            v = mpmath.tanh(mpmath.mpf(x))
            hi = round_nearest(v)
            f.write(f"{bits(x):016x} {bits(hi):016x} {bits(frac(v, hi)):016x}\n")
    with open(os.path.join(out, "hypot64_reference.txt"), "w") as f:
        f.write(f"# x y hypot(x, y) frac: IEEE 754 binary64 bits, correctly rounded, and (true - rounded) / its ulp (mpmath, 400 bits)\n")
        f.write(f"# generated by scripts/gen_tanh_hypot64_reference.py (seed {SEED}, N_HYPOT {n_hypot})\n")
        for x, y in hypot_inputs(rng, n_hypot):
            v = mpmath.sqrt(mpmath.mpf(x) ** 2 + mpmath.mpf(y) ** 2)
            hi = round_nearest(v)
            f.write(f"{bits(x):016x} {bits(y):016x} {bits(hi):016x} {bits(frac(v, hi)):016x}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
