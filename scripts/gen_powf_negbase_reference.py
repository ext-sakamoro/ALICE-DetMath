#!/usr/bin/env python3
"""Generate tests/data/powf_negbase_reference.txt: correctly rounded `powf` of
a negative base with an integer exponent.

IEEE 754 `pow(x, n)` for `x < 0` and an integer `n` is `±|x|^n`, negative when
`n` is odd. Each input pair is a pair of exact binary32 values, `mpmath`
evaluates `x^n` exactly enough (400 bits) and the result is rounded to the
nearest binary32 (ties to even) by comparing the candidates around it in high
precision, subnormals and overflow to infinity included. No libm is used.

Inputs: bases `-2^k` for k in [-10, 10] (exact powers, so the integer results
are exact), `-1`, decimal bases `-0.1 .. -100`, a geometric sweep of 40 bases
in [-1e3, -1e-3], and the first 2^-149 / largest finite bases; exponents every
integer in [-40, 40] and the large odd / even exponents that still give a
finite result for bases near -1.

Each line: `<x bits> <y bits> <powf(x, y) bits>`, 8 hex digits each.

Usage: `uv run --with mpmath python3 scripts/gen_powf_negbase_reference.py`
(or any Python with mpmath installed). The output is deterministic.
"""

from __future__ import annotations

import os
import struct

import mpmath as mp

mp.mp.prec = 400


def f32(v: float) -> float:
    return struct.unpack("<f", struct.pack("<f", v))[0]


def bits(v: float) -> int:
    return struct.unpack("<I", struct.pack("<f", v))[0]


def from_bits(b: int) -> float:
    return struct.unpack("<f", struct.pack("<I", b))[0]


MAX32 = from_bits(0x7F7FFFFF)


def round_f32(v: mp.mpf) -> float:
    """The binary32 nearest `v` (ties to even), with overflow to infinity."""
    if v == 0:
        return 0.0
    neg = v < 0
    a = -v if neg else v
    # IEEE overflow: at or above MAX + half an ulp (2^104) rounds to infinity
    if a >= mp.mpf(MAX32) + mp.mpf(2) ** 103:
        r = float("inf")
    else:
        c = bits(f32(min(float(a), MAX32)))
        best = None
        for b in (c - 1, c, c + 1):
            if b < 0 or b > 0x7F7FFFFF:
                continue
            d = abs(mp.mpf(from_bits(b)) - a)
            if best is None or d < best[0] or (d == best[0] and b % 2 == 0):
                best = (d, b)
        r = from_bits(best[1])
    return -r if neg else r


def main() -> None:
    bases = [-(2.0 ** k) for k in range(-10, 11)] + [-1.0]
    bases += [-0.1, -0.3, -0.7, -1.5, -3.0, -7.0, -10.0, -12.5, -100.0]
    bases += [-f32(float(mp.mpf(10) ** (-3 + 6 * i / 39))) for i in range(40)]
    bases += [-from_bits(1), -MAX32, -from_bits(0x3F7FFFFF), -from_bits(0x3F800001)]
    exps = list(range(-40, 41)) + [101, 1001, 10001, -10001, 1000, 10000, -10000]
    seen = set()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "tests", "data", "powf_negbase_reference.txt")
    out = open(path, "w", encoding="utf-8", newline="\n")
    out.write("# x y powf(x, y): IEEE 754 binary32 bits, correctly rounded (mpmath, 400 bits)\n")
    out.write("# generated by scripts/gen_powf_negbase_reference.py\n")
    for x in bases:
        x = f32(x)
        for n in exps:
            if n == 0 or (x, n) in seen:
                continue
            seen.add((x, n))
            v = mp.power(mp.mpf(x), n)
            out.write(f"{bits(x):08x} {bits(float(n)):08x} {bits(round_f32(v)):08x}\n")

    out.close()
    print(path)


if __name__ == "__main__":
    main()
