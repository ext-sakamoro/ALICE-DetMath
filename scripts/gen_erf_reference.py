#!/usr/bin/env python3
"""Generate tests/data/erf64_reference.txt and tests/data/erf32_reference.txt:
correctly rounded erf.

The reference is independent of every libm: each input is an exact binary
double (or single), `mpmath` evaluates erf at 2400 bits, and the result is
rounded to the nearest double (or single), ties to even, by comparing the
three candidates around it in high precision.

Inputs (all finite, both signs): zero and the smallest magnitudes, the
`|x| < 2^-28` shortcut, every branch boundary of the fdlibm algorithm
(0.84375, 1.25, the 1/0.35 switch, 6) with their neighbours, the saturation region
(where erf rounds to ±1), small arguments by powers of two, a uniform sweep
of [-6.5, 6.5] (where erf is not ±1), and the activation range [-8, 8] at a
fine step.

Each line: `<x bits> <erf(x) bits>`, 16 hex digits each for binary64 and
8 for binary32.

Usage: `uv run --with mpmath python3 scripts/gen_erf_reference.py`
(or any Python with mpmath installed). The output is deterministic.
"""

from __future__ import annotations

import math
import os
import random
import struct

import mpmath

mpmath.mp.prec = 2400

# src/double.rs::erf64 branch boundaries
# (the 1/0.35 switch is fdlibm's high word 0x4006db6d with a zero low word)
BOUNDS = (0.84375, 1.25, 2.8571414947509766, 6.0)


def bits64(x: float) -> int:
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def bits32(x: float) -> int:
    return struct.unpack("<I", struct.pack("<f", x))[0]


def from_bits64(b: int) -> float:
    return struct.unpack("<d", struct.pack("<Q", b))[0]


def from_bits32(b: int) -> float:
    return struct.unpack("<f", struct.pack("<I", b))[0]


def to_f32(x: float) -> float:
    return struct.unpack("<f", struct.pack("<f", x))[0]


def next32(x: float, up: bool) -> float:
    b = bits32(x)
    if x == 0.0:
        return from_bits32(1) if up else -from_bits32(1)
    if (x > 0) == up:
        return from_bits32(b + 1)
    return from_bits32(b - 1)


def round_nearest64(v: mpmath.mpf) -> float:
    c = float(v)
    best = None
    for cand in (math.nextafter(c, -math.inf), c, math.nextafter(c, math.inf)):
        key = (abs(mpmath.mpf(cand) - v), bits64(cand) & 1)
        if best is None or key < best[0]:
            best = (key, cand)
    return best[1]


def round_nearest32(v: mpmath.mpf) -> float:
    c = to_f32(float(v))
    best = None
    for cand in (next32(c, False), c, next32(c, True)):
        key = (abs(mpmath.mpf(cand) - v), bits32(cand) & 1)
        if best is None or key < best[0]:
            best = (key, cand)
    return best[1]


def neighbours64(x: float, n: int) -> list[float]:
    out = [x]
    up = down = x
    for _ in range(n):
        up = math.nextafter(up, math.inf)
        down = math.nextafter(down, -math.inf)
        out += [up, down]
    return out


def neighbours32(x: float, n: int) -> list[float]:
    x = to_f32(x)
    out = [x]
    up = down = x
    for _ in range(n):
        up = next32(up, True)
        down = next32(down, False)
        out += [up, down]
    return out


def signed(xs: list[float]) -> list[float]:
    return xs + [-x for x in xs]


def inputs64() -> list[float]:
    rng = random.Random(20261027)
    xs: list[float] = [0.0, from_bits64(1), 2.2250738585072014e-308]
    for e in range(0, 1075, 3):
        xs.append(math.ldexp(1.0, -e))
    xs += neighbours64(math.ldexp(1.0, -28), 4)
    for b in BOUNDS:
        xs += neighbours64(b, 6)
    # saturation: erf(x) rounds to 1 near x = 5.92 in binary64
    for i in range(200):
        xs.append(5.8 + 0.4 * i / 199)
    xs += [27.9, 28.0, 28.1, 1e3, 1e300]
    for _ in range(1500):
        xs.append(rng.uniform(0.0, 6.5))
    for i in range(1601):
        xs.append(-8.0 + 16.0 * i / 1600)
    return dedup(signed(xs), bits64)


def inputs32() -> list[float]:
    rng = random.Random(20261028)
    xs: list[float] = [0.0, from_bits32(1)]
    for e in range(0, 150, 2):
        xs.append(math.ldexp(1.0, -e))
    for b in BOUNDS:
        xs += neighbours32(b, 6)
    # saturation: erf(x) rounds to 1 near x = 3.92 in binary32
    for i in range(200):
        xs.append(to_f32(3.8 + 0.3 * i / 199))
    xs += [10.0, 1e30]
    for _ in range(2500):
        xs.append(to_f32(rng.uniform(0.0, 4.5)))
    for i in range(1601):
        xs.append(to_f32(-8.0 + 16.0 * i / 1600))
    return dedup(signed([to_f32(x) for x in xs]), bits32)


def dedup(xs: list[float], key) -> list[float]:
    out, seen = [], set()
    for x in xs:
        k = key(x)
        if k not in seen and math.isfinite(x):
            seen.add(k)
            out.append(x)
    return sorted(out)


HEADER = (
    "# x erf(x): IEEE 754 binary{w} bits, correctly rounded (mpmath, 2400 bits)\n"
    "# generated by scripts/gen_erf_reference.py\n"
    "# Not produced by any libm: a libm that is correctly rounded on one\n"
    "# machine and a ulp off on another would make the bound depend on the\n"
    "# machine rather than on this crate.\n"
)


def main() -> None:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    data = os.path.join(root, "tests", "data")
    os.makedirs(data, exist_ok=True)
    rows = [f"{bits64(x):016x} {bits64(round_nearest64(mpmath.erf(mpmath.mpf(x)))):016x}" for x in inputs64()]
    with open(os.path.join(data, "erf64_reference.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(w=64) + "\n".join(rows) + "\n")
    print(f"{len(rows)} inputs -> erf64_reference.txt")
    rows = [f"{bits32(x):08x} {bits32(round_nearest32(mpmath.erf(mpmath.mpf(x)))):08x}" for x in inputs32()]
    with open(os.path.join(data, "erf32_reference.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(w=32) + "\n".join(rows) + "\n")
    print(f"{len(rows)} inputs -> erf32_reference.txt")


if __name__ == "__main__":
    main()
