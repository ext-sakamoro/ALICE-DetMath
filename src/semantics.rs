const fn same_name(a: &str, b: &str) -> bool {
    let (a, b) = (a.as_bytes(), b.as_bytes());
    if a.len() != b.len() {
        return false;
    }
    let mut i = 0;
    while i < a.len() {
        if a[i] != b[i] {
            return false;
        }
        i += 1;
    }
    true
}

/// The identifier of the function named `name` in [`FUNCTION_PINS`]. In a const context an unknown
/// name stops the compile (a misspelt or removed function cannot fold silently).
///
/// # Panics
///
/// When `name` is not in [`FUNCTION_PINS`].
#[must_use]
pub const fn function_pin(name: &str) -> [u8; 32] {
    let mut i = 0;
    while i < FUNCTION_PINS.len() {
        if same_name(FUNCTION_PINS[i].0, name) {
            return FUNCTION_PINS[i].1;
        }
        i += 1;
    }
    panic!("not a function of alice-det-math (no entry in FUNCTION_PINS)");
}
